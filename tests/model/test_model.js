/* Model.gs PP_mdlCompileFlow_ as it was before the graph (frozen copy, 23 Oct 2026): the list the rows gave. */
function OLD_COMPILE_FLOW(screens) {
  return screens.filter(screen => screen.active).map(screen => {
    const entry = { id: screen.id, type: screen.type };
    if (screen.text) entry.text = screen.text;
    if (screen.options.length) entry.options = screen.options.slice();
    ['low_label', 'high_label', 'scale_hint', 'body'].forEach(field => {
      if (screen[field]) entry[field] = screen[field];
    });
    if (typeof screen.required === 'boolean') entry.required = screen.required;
    if (screen.show_if && Object.prototype.toString.call(screen.show_if) === '[object Object]' && !('unreadable' in screen.show_if)) {
      entry.show_if = JSON.parse(JSON.stringify(screen.show_if));
    }
    if (screen.skip_if) entry.skip_if = screen.skip_if;
    return entry;
  });
}

/* The compiled route equals PP.flow.fromLegacy of the list the rows always gave, byte for byte. */
