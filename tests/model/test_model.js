function lineDiff(actual, expected) {
  const a = actual.split('\n');
  const e = expected.split('\n');
  const out = [];
  const length = Math.max(a.length, e.length);
  for (let i = 0; i < length; i++) {
    if (a[i] !== e[i]) out.push({ line: i + 1, exported: a[i], repo: e[i] });
  }
  return out;
}

