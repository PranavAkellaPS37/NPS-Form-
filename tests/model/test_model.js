/* tests/flow/cases/<name>.json as a questionnaire, built exactly like tests/flow/check_test.js does. */
const CASES_DIR = path.join(ROOT, 'tests/flow/cases');
function caseSurvey(c) {
  const base = JSON.parse(fs.readFileSync(path.join(CASES_DIR, '_base.json'), 'utf8'));
  const survey = plain(base.survey);
  survey.flow = plain(c.base === 'list' ? base.flow_list : base.flow_graph);
  Object.keys(c.survey || {}).forEach(k => { survey[k] = plain(c.survey[k]); });
  const find = (list, id) => {
    for (let i = 0; i < list.length; i++) {
      const n = list[i];
      if (n && n.id === id) return [list, i];
      if (n && n.type === 'group' && n.body && Array.isArray(n.body.nodes)) { const f = find(n.body.nodes, id); if (f) return f; }
    }
    return null;
  };
  (c.patch || []).forEach(p => {
    if (p.op === 'set_flow') { survey.flow[p.field] = plain(p.value); return; }
    const at = find(Array.isArray(survey.flow) ? survey.flow : survey.flow.nodes, p.op === 'add' ? p.after : p.node);
    if (!at) throw new Error('case patch: no node ' + (p.after || p.node));
    const [list, i] = at;
    if (p.op === 'set') list[i][p.field] = plain(p.value);
    else if (p.op === 'remove_field') delete list[i][p.field];
    else if (p.op === 'remove') list.splice(i, 1);
    else if (p.op === 'replace') list[i] = plain(p.value);
    else if (p.op === 'add') list.splice(i + 1, 0, plain(p.value));
  });
  const strings = plain(base.strings);
  (c.strings_set || []).forEach(([key, lang, text]) => { strings[key][lang] = text; });
  (c.strings_delete || []).forEach(([key, lang]) => { if (lang) delete strings[key][lang]; else delete strings[key]; });
  return { survey, strings };
}

